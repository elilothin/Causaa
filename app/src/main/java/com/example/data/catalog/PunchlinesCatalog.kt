    val allPunchlines: List<String> = punchlines.values.flatten()

    fun randomFor(category: PunchlineCategory, seedOffset: Int = 0): String {
        val list = punchlines[category].orEmpty()
        if (list.isEmpty()) return "Chaque effort est une cause."
        val idx = ((System.currentTimeMillis() / 1000L + seedOffset).toInt().let { kotlin.math.abs(it) }) % list.size
        return list[idx]
    }

    fun dailyPunchline(dayOfYear: Int): String {
        if (allPunchlines.isEmpty()) return "Forge-toi."
        return allPunchlines[kotlin.math.abs(dayOfYear) % allPunchlines.size]
    }

